def _normalize(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").strip())


# 平台侧共情句（情绪 + 学习请求时，放在回答最前面那一句）
_EMPATHY_LINES: dict[str, str] = {
    "crisis": "先别管题目 —— 你现在最重要的是安全。",
    "sadness": "先说一句：你现在难受，是很正常的事。",
    "anxiety": "别急，我们一步一步来。",
    "anger": "烦就先烦一会儿，我不催你。",
    "self_doubt": "「不会」不等于笨，我们从最小的一步开始。",
    "tired": "累了就先歇口气，这道题不急。",
    "lonely": "你愿意说，我就在听。",
}


def classify(text: str) -> str | None:
    """返回命中的情绪类别（crisis/sadness/…），没命中返回 None。"""
    t = _normalize(text).lower()
    if not t:
        return None
    for name, keys in _EMOTION_TABLE:
        for k in keys:
            if k in t:
                return name
    return None


def is_study_request(text: str) -> bool:
    """消息里是否包含「真的要问学习问题」的迹象。"""
    t = _normalize(text)
    return any(m in t for m in _STUDY_MARKERS)


def reply(text: str) -> tuple[str, str] | None:
    """纯情绪消息 -> (类别, 安慰语)；情绪 + 学习请求 -> None（交给答疑链路）。

    注意：**危机类**永远直接安慰，不管有没有学习请求 —— 那种时候题目不重要。
    """
    cat = classify(text)
    if not cat:
        return None
    if cat != "crisis" and is_study_request(text):
        return None
    variants = _REPLIES.get(cat) or ()
    if not variants:
        return None
    # 同一个消息稳定选同一条，不同消息之间有变化（避免每次都是同一句）
    pick = sum(ord(c) for c in text) % len(variants)
    return cat, variants[pick]


def empathy_line(text: str) -> str:
    """情绪 + 学习请求时，**由平台侧给出**的一句安慰（放在回答最前面）。

    为什么不靠提示词：实测本地 3B 模型会**完全无视**提示词里的「先共情再作答」，
    张口就讲知识点（2026-09-27 实测：问「我好烦，这题还是不会，帮我讲讲单调性」，
    回答第一句就是单调性的定义）。所以这句必须平台自己给，模型是否听话都不影响。
    """
    cat = classify(text)
    if not cat:
        return ""
    return _EMPATHY_LINES.get(cat, "")


def study_hint(text: str) -> str:
    """情绪 + 学习请求时，给模型的额外指示（插进提示词，不当正文展示）。"""
    cat = classify(text)
    if not cat:
        return ""
    if cat == "crisis":
        return "学生情绪非常低落，请先用一两句话表达关心，再谈学习；不要只讲知识点。"
    return (
        "学生此刻带着%s的情绪。**平台已经在回答开头替你说了一句安慰**，"
        "所以你**不要重复安慰、不要再说「我理解你」这类话**，直接从题目讲解开始；"
        "但语气保持温和，不要冷冰冰地甩知识点。"
        % {"sadness": "难过/失落", "anxiety": "紧张/焦虑", "anger": "烦躁",
           "self_doubt": "自我怀疑", "tired": "疲惫/想放弃", "lonely": "孤独感"}
        .get(cat, "低落")
    )
