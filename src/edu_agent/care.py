"""情绪关心短路：用户情绪低落时**先说人话安慰，而不是甩数学知识点**（2026-09-27）。

为什么要它：
    聊天链路（答疑 A）的设计是「依据教材作答」—— 先检索教材、把命中的片段塞进提示词，
    再要求模型按协议作答。用户发「我这次考砸了，好难过」时，检索照样会跑，
    返回几段无关的教材内容，本地小模型于是顺着它们讲起了知识点 —— 情绪被完全无视。
    这在教育场景里是明显不合适的。

两级处理（关键设计）：
    1) **纯情绪 / 宣泄 / 自我否定**（消息里没有具体学科请求）
       -> 直接给一句安慰（`reply()`），不检索、不调模型，毫秒级返回。
    2) **情绪 + 学习请求**（例如「我好烦，这道题还是不会做，帮我讲讲单调性」）
       -> **正常走答疑链路**，但额外注入一条「先共情再作答」的提示（`study_hint()`），
          既不耽误解题，也不冷冰冰。绝不把这类消息短路成纯安慰 —— 那会答非所问。

安全提示：识别到自伤/轻生倾向时给的是「找可信的人 / 学校心理老师 / 紧急情况打 110、120」
这类**真实可执行**的建议；不编造任何热线号码。

规则是显式关键词表（可扩展）：`_EMOTION_TABLE` 与 `_STUDY_MARKERS` 都在本文件里，
要加词直接加，不影响其它链路。
"""
